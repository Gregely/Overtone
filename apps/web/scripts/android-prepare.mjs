// Generates Android resources that derive from apps/web/app.config.json:
//  - res/xml/network_security_config.xml (cleartext policy)
// Run via `npm run android:sync`.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const web = fileURLToPath(new URL('..', import.meta.url));
const cfg = JSON.parse(readFileSync(`${web}app.config.json`, 'utf8'));

/**
 * Android's network security config matches host NAMES (with subdomains) or
 * exact IPs; it cannot express IP ranges. So cleartext is allowed for local
 * name suffixes below, plus any exact private IPs listed in cleartextHosts.
 */
const LOCAL_SUFFIXES = ['localhost', 'local', 'lan', 'home', 'internal', 'home.arpa', 'ts.net'];
const PRIVATE_IP = /^(10\.\d+\.\d+\.\d+|192\.168\.\d+\.\d+|172\.(1[6-9]|2\d|3[01])\.\d+\.\d+|100\.(6[4-9]|[7-9]\d|1[01]\d|12[0-7])\.\d+\.\d+|127\.\d+\.\d+\.\d+)$/;
const NAME = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)*$/i;

const extra = (cfg.cleartextHosts ?? []).map((h) => String(h).trim().toLowerCase()).filter(Boolean);
for (const h of extra) {
  const isIp = /^\d+\.\d+\.\d+\.\d+$/.test(h);
  if (isIp && !PRIVATE_IP.test(h)) throw new Error(`cleartextHosts: ${h} is a public IP. Plain HTTP is only allowed to private addresses; use HTTPS.`);
  if (!isIp && !LOCAL_SUFFIXES.some((s) => h === s || h.endsWith(`.${s}`))) {
    throw new Error(`cleartextHosts: ${h} is not a local name (.local, .lan, .home.arpa, .internal, .ts.net). Use HTTPS for public hosts.`);
  }
  if (!isIp && !NAME.test(h)) throw new Error(`cleartextHosts: invalid host ${h}`);
}

const xml = `<?xml version="1.0" encoding="utf-8"?>
<!--
  GENERATED by apps/web/scripts/android-prepare.mjs from app.config.json. Do not edit.

  Plain HTTP is refused everywhere except local-network names and the exact
  private IPs listed in app.config.json "cleartextHosts". HTTPS (e.g. Tailscale
  "tailscale serve", or Caddy) is the recommended way to reach your server.
  Android cannot express IP ranges here, which is why private IPs must be listed.
-->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
    <domain-config cleartextTrafficPermitted="true">
${LOCAL_SUFFIXES.map((d) => `        <domain includeSubdomains="true">${d}</domain>`).join('\n')}
        <!-- Android emulator's alias for the host machine -->
        <domain includeSubdomains="false">10.0.2.2</domain>
        <domain includeSubdomains="false">127.0.0.1</domain>
${extra.map((h) => `        <domain includeSubdomains="${/^\d/.test(h) ? 'false' : 'true'}">${h}</domain>`).join('\n')}
    </domain-config>
</network-security-config>
`;
const dir = `${web}android/app/src/main/res/xml`;
mkdirSync(dir, { recursive: true });
writeFileSync(`${dir}/network_security_config.xml`, xml.replace(/\n\n/g, '\n'));
console.log(`network_security_config.xml: cleartext for ${LOCAL_SUFFIXES.length} local suffixes + ${extra.length} extra host(s)`);
